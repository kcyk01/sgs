/**
 * Reduces every character's artwork to the 280-byte descriptor the camera
 * scanner matches against, and writes them out as a module.
 *
 *   public/cards/liu-bei.webp  ->  ['liu-bei', 'liu-bei', 'f4uGb2h...']
 *
 * Build-time only, same arrangement as build-card-colors.mjs: it lives outside
 * `src/`, nothing imports it, and `sharp` is a devDependency. The *output* is
 * checked in, so the app never does image work at startup.
 *
 *   npm run descriptors            regenerate the reference module
 *   npm run descriptors -- --dry   print it instead of writing it
 *
 * ## Why this imports from src/
 *
 * `describe()` is pulled straight out of the app's own pipeline rather than
 * reimplemented here. That is not a convenience — it is a correctness
 * requirement. A reference descriptor and a camera descriptor are only
 * comparable if the exact same arithmetic produced them, and two copies of this
 * logic would drift apart silently, showing up as a scanner that gradually stops
 * working rather than as a failing build. Node 24 strips the types natively
 * (`erasableSyntaxOnly` in tsconfig.app.json keeps every file in `src/`
 * strippable), which is also why imports inside `pipeline/` carry explicit `.ts`
 * extensions.
 *
 * Characters only. Weapon cards are excluded deliberately: they have a different
 * layout, so the artwork window the scanner crops does not apply to them, and
 * including them would only add wrong answers for the matcher to pick.
 *
 * Flags: --in <dir> --out <file> --dry
 */
import { readdir, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import sharp from 'sharp'

import { describe, encodeDescriptor } from '../src/features/scan/pipeline/descriptor.ts'
import { CARD_WIDTH } from '../src/features/scan/pipeline/rectify.ts'
import { characterVersions } from '../src/lib/versions.ts'
// The per-kingdom files rather than `data/characters/index.ts`, which runs an
// `import.meta.env.DEV` duplicate-id check that only exists under Vite.
import { qun } from '../src/data/characters/qun.ts'
import { shu } from '../src/data/characters/shu.ts'
import { wei } from '../src/data/characters/wei.ts'
import { wu } from '../src/data/characters/wu.ts'

const args = process.argv.slice(2)
const flag = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i === -1 ? fallback : args[i + 1]
}

const inDir = path.resolve(flag('in', 'public/cards'))
const outFile = path.resolve(
  flag('out', 'src/features/scan/model/references.ts'),
)
const dry = args.includes('--dry')

const characters = [...shu, ...wei, ...wu, ...qun]

/**
 * Loads a reference image as a raster the pipeline understands.
 *
 * Resized to `CARD_WIDTH` first so it enters `describe()` at the same scale a
 * warped camera frame does. The descriptor area-averages anyway, so this changes
 * the numbers barely at all — but "barely at all" is worth removing when the
 * whole design rests on the two sides being computed identically, and it makes
 * the run ~10x faster as a side effect.
 */
async function loadArtwork(file) {
  const { data, info } = await sharp(file)
    .resize({ width: CARD_WIDTH, fit: 'inside', withoutEnlargement: true })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })

  return {
    data: new Uint8ClampedArray(data.buffer, data.byteOffset, data.length),
    width: info.width,
    height: info.height,
  }
}

const available = await readdir(inDir).catch(() => null)
if (!available) {
  console.error(`No card directory at ${path.relative(process.cwd(), inDir)}`)
  process.exit(1)
}

const byBasename = new Map(
  available
    .filter((f) => /\.(webp|png|jpe?g|avif)$/i.test(f))
    .map((f) => [path.basename(f, path.extname(f)), f]),
)

const entries = []
const missing = []

for (const character of characters)
  for (const version of characterVersions(character)) {
    const file = byBasename.get(version.id)
    if (!file) {
      missing.push(version.id)
      continue
    }
    const descriptor = describe(await loadArtwork(path.join(inDir, file)))
    entries.push([version.id, version.baseId, encodeDescriptor(descriptor)])
  }

// Sorted by art id so a re-run diffs only where the art actually changed, rather
// than wherever the data files happened to be reordered.
entries.sort(([a], [b]) => a.localeCompare(b))

const body = entries
  .map(([artId, baseId, encoded]) => `  ['${artId}', '${baseId}', '${encoded}'],`)
  .join('\n')

const module = `/**
 * Precomputed artwork descriptors, one row per character printing.
 *
 * GENERATED by scripts/build-card-descriptors.mjs — do not edit by hand. Re-run
 * \`npm run descriptors\` after adding a character or changing any art in
 * public/cards.
 *
 * Each row is [art id, character id, base64 descriptor]. The art id is the
 * filename in public/cards; the character id is the \`/c/:id\` route the match
 * resolves to, which differs for alternate printings. See
 * features/scan/pipeline/descriptor.ts for what the ${entries[0]?.[2].length ?? 0} base64 characters
 * decode to.
 *
 * Characters only — weapons are excluded, see the generating script.
 *
 * Deliberately *not* in src/data/: vite.config.ts puts that directory in an
 * eagerly-loaded chunk, and this table is only ever needed by the lazily-routed
 * scanner. Here it rides along with the scan chunk and costs other visits
 * nothing.
 */

/** [art id, character id, base64 descriptor] */
export type ReferenceRow = readonly [string, string, string]

export const REFERENCE_ROWS: readonly ReferenceRow[] = [
${body}
]
`

if (dry) {
  process.stdout.write(module)
} else {
  await mkdir(path.dirname(outFile), { recursive: true })
  await writeFile(outFile, module, 'utf8')
  console.log(
    `${entries.length} printings -> ${path.relative(process.cwd(), outFile)}`,
  )
}

if (missing.length)
  console.warn(
    `No artwork for ${missing.length} printing(s): ${missing.join(', ')}. ` +
      `The scanner cannot match a card it has no reference image for — add ` +
      `the art to art-source/ and run \`npm run images\`.`,
  )
